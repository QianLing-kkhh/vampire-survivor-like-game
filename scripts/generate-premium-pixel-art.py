def generate_tier_assets() -> list[Asset]:
    result: list[Asset] = []
    for weapon in WEAPON_IDS:
        for tier in (1, 2, 3):
            icon_path = f"weapons/{weapon}_icon_tier{tier}.png"
            icon_key = f"art_weapons_{weapon}_icon_tier{tier}"
            icon_asset = make_asset(icon_path, icon_key, "image", 64, 64, 1)
            image = transparent_canvas(64, 64)
            draw_weapon_symbol(image, weapon, tier, 0, False)
            save_asset(icon_asset, image)
            result.append(icon_asset)

            sheet_path = f"weapons/{weapon}_projectile_tier{tier}_sheet.png"
            sheet_key = f"art_weapons_{weapon}_projectile_tier{tier}_sheet"
            sheet_asset = make_asset(sheet_path, sheet_key, "spritesheet", 64, 64, 4)
            sheet = transparent_canvas(256, 64)
            for frame in range(4):
                cell = transparent_canvas(64, 64)
                draw_weapon_symbol(cell, weapon, tier, frame, True)
                sheet.alpha_composite(cell, (frame * 64, 0))
            save_asset(sheet_asset, sheet)
            result.append(sheet_asset)

    for passive in PASSIVE_IDS:
        for tier in (1, 2, 3):
            path = f"passives/{passive}_icon_tier{tier}.png"
            key = f"art_passives_{passive}_icon_tier{tier}"
            asset = make_asset(path, key, "image", 64, 64, 1)
            image = transparent_canvas(64, 64)
            draw_passive_symbol(image, passive, tier)
            save_asset(asset, image)
            result.append(asset)

    return result


def make_asset(path: str, key: str, kind: str, fw: int, fh: int, frames: int) -> Asset:
    raw = {"path": path, "key": key, "type": kind, "frameWidth": fw, "frameHeight": fh, "frames": frames}
    return parse_asset(raw)


def save_asset(asset: Asset, image: Image.Image) -> None:
    path = ART_ROOT / asset.path
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path)


