@dataclass(frozen=True)
class Asset:
    path: str
    key: str
    type: str
    frame_width: int
    frame_height: int
    frames: int
    raw: dict[str, Any]


def main() -> None:
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    assets = [parse_asset(raw) for raw in manifest["assets"]]
    assets = merge_assets([
        *assets,
        *(make_asset(*extra) for extra in EXTRA_MANIFEST_ASSETS),
    ])
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup_dir = TMP_ROOT / "backups" / stamp / "art"
    review_dir = TMP_ROOT / "review" / stamp
    backup_art(backup_dir)

    generated_assets: list[Asset] = []
    for asset in assets:
        out_path = ART_ROOT / asset.path
        out_path.parent.mkdir(parents=True, exist_ok=True)
        image = render_asset(asset)
        image.save(out_path)
        generated_assets.append(asset)

    tier_assets = generate_tier_assets()
    for tier_asset in tier_assets:
        generated_assets.append(tier_asset)

    manifest["style"] = "Premium high-definition pixel art, readable top-down action RPG sprites, distinct upgrade tiers"
    manifest["version"] = f"premium-pixel-full-regen-{stamp}"
    manifest["notes"] = [
        "Generated by scripts/generate-premium-pixel-art.py.",
        "Transparent RGBA PNGs are used for characters, objects, weapons, effects, and UI overlays.",
        "World tiles intentionally fill the full canvas for seamless map rendering.",
        "Weapon and passive tier variants use visibly stronger silhouette, color, glow, and ornamentation per tier.",
        "Review output includes a tier progression sheet for side-by-side level readability checks.",
    ]
    manifest["assets"] = [asset.raw for asset in merge_assets(generated_assets)]
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    render_review_sheets(review_dir, merge_assets(generated_assets))
    render_tier_progression_review(review_dir)
    print(f"backup={backup_dir}")
    print(f"review={review_dir}")
    print(f"assets={len(merge_assets(generated_assets))}")


def parse_asset(raw: dict[str, Any]) -> Asset:
    return Asset(
        path=raw["path"],
        key=raw["key"],
        type=raw["type"],
        frame_width=int(raw["frameWidth"]),
        frame_height=int(raw["frameHeight"]),
        frames=int(raw["frames"]),
        raw=dict(raw),
    )


def backup_art(backup_dir: Path) -> None:
    if backup_dir.exists():
        shutil.rmtree(backup_dir)
    shutil.copytree(ART_ROOT, backup_dir, ignore=shutil.ignore_patterns("animation_manifest.json"))
    backup_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(MANIFEST_PATH, backup_dir / "animation_manifest.json")


def merge_assets(assets: list[Asset]) -> list[Asset]:
    by_key: dict[str, Asset] = {}
    for asset in assets:
        by_key[asset.key] = asset
    return list(by_key.values())


def image_size_for(asset: Asset) -> tuple[int, int]:
    current = ART_ROOT / asset.path
    if current.exists():
        try:
            with Image.open(current) as image:
                return image.size
        except Exception:
            pass

    if asset.type == "spritesheet":
        if asset.raw.get("rows") and asset.raw.get("columns"):
            return asset.frame_width * int(asset.raw["columns"]), asset.frame_height * int(asset.raw["rows"])
        return asset.frame_width * asset.frames, asset.frame_height
    return asset.frame_width, asset.frame_height


def render_asset(asset: Asset) -> Image.Image:
    path = asset.path.replace("\\", "/")
    if path.startswith("player/"):
        return render_player_asset(asset)
    if path.startswith("weapons/"):
        return render_weapon_asset(asset, tier=1)
    if path.startswith("passives/"):
        return render_passive_asset(asset, tier=1)
    if path.startswith("enemies/"):
        return render_enemy_asset(asset)
    if path.startswith("effects/"):
        return render_effect_asset(asset, tier=1)
    if path.startswith("pickups/"):
        return render_pickup_asset(asset)
    if path.startswith("ui/"):
        return render_ui_asset(asset)
    if path.startswith("world/"):
        return render_world_asset(asset)
    if path.startswith("map-mechanics/"):
        return render_map_mechanic_asset(asset)
    return transparent_canvas(*image_size_for(asset))


def render_player_asset(asset: Asset) -> Image.Image:
    path = asset.path.replace("\\", "/")
    parts = path.split("/")
    size = image_size_for(asset)

    if len(parts) >= 3 and parts[1] in PALETTES:
        skin = parts[1]
        name = parts[-1]
        if name.startswith("walk_") and name != "walk_8dir_sheet.png":
            direction = name.removeprefix("walk_").removesuffix(".png")
            return render_player_strip(skin, "walk", direction)
        if name.startswith("idle_"):
            direction = name.removeprefix("idle_").removesuffix(".png")
            return render_player_strip(skin, "idle", direction)
        if name == "walk_8dir_sheet.png":
            return stack_direction_sheets([render_player_strip(skin, "walk", direction) for direction in DIRECTIONS])
        if name == "idle_8dir_sheet.png":
            return stack_direction_sheets([render_player_strip(skin, "idle", direction) for direction in DIRECTIONS])
        if name == "portrait.png":
            return render_portrait(skin)
        if name == "hit_fx.png":
            return render_burst(size[0], size[1], PALETTES[skin]["trim"], rings=3)
        if name in ("blink_trail.png", "blink_flash.png", "slow_zone.png", "sanctuary_circle.png", "counter_wave.png"):
            return render_skill_effect(size[0], size[1], PALETTES[skin]["trim"], name)

    if path.endswith("_walk_sheet.png") or path.endswith("player_walk_sheet.png"):
        skin = next((skin_id for skin_id in PALETTES if skin_id in path), "assassin_default")
        return render_player_strip(skin, "walk", "down")

    return transparent_canvas(*size)


def render_player_strip(skin: str, state: str, direction: str) -> Image.Image:
    sheet = transparent_canvas(320, 80)
    for frame in range(4):
        cell = transparent_canvas(80, 80)
        draw_player_frame(cell, skin, state, direction, frame)
        sheet.alpha_composite(cell, (frame * 80, 0))
    return sheet


