def transparent_canvas(width: int, height: int) -> Image.Image:
    return Image.new("RGBA", (width, height), (0, 0, 0, 0))


def add_pixel_polish(image: Image.Image) -> Image.Image:
    image = image.convert("RGBA")
    glow = Image.new("RGBA", image.size, (0, 0, 0, 0))
    alpha = image.getchannel("A")
    glow.putalpha(alpha.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.GaussianBlur(1.0)))
    tint = Image.new("RGBA", image.size, (125, 211, 252, 22))
    glow = Image.alpha_composite(glow, tint)
    out = Image.alpha_composite(glow, image)
    return out


def rounded(draw: ImageDraw.ImageDraw, box: tuple[float, float, float, float], radius: int, fill=None, outline=None) -> None:
    draw.rounded_rectangle(tuple(int(v) for v in box), radius=radius, fill=fill, outline=outline)


def add_highlight(draw: ImageDraw.ImageDraw, box: tuple[int, int, int, int], color: tuple[int, int, int, int]) -> None:
    x1, y1, x2, y2 = box
    draw.line((x1 + 2, y1 + 2, x2 - 3, y1 + 2), fill=add_alpha(shade(color, 50), 120), width=2)


def add_sprite_sparkle(
    draw: ImageDraw.ImageDraw,
    x: float,
    y: float,
    color: tuple[int, int, int, int],
    frame: int,
) -> None:
    if frame % 2 != 0:
        return

    draw.rectangle((x - 1, y - 3, x + 1, y + 3), fill=add_alpha(shade(color, 65), 130))
    draw.rectangle((x - 3, y - 1, x + 3, y + 1), fill=add_alpha(shade(color, 65), 130))


def star(draw: ImageDraw.ImageDraw, cx: float, cy: float, radius: float, fill, outline=None) -> None:
    points = []
    for i in range(10):
        angle = -math.pi / 2 + i * math.pi / 5
        r = radius if i % 2 == 0 else radius * 0.42
        points.append((cx + math.cos(angle) * r, cy + math.sin(angle) * r))
    draw.polygon(points, fill=fill, outline=outline)


def rotate_points(points: list[tuple[float, float]], cx: float, cy: float, degrees: float) -> list[tuple[float, float]]:
    angle = math.radians(degrees)
    result = []
    for x, y in points:
        dx, dy = x - cx, y - cy
        result.append((cx + dx * math.cos(angle) - dy * math.sin(angle), cy + dx * math.sin(angle) + dy * math.cos(angle)))
    return result


def shade(color: tuple[int, int, int, int], amount: int) -> tuple[int, int, int, int]:
    return (
        max(0, min(255, color[0] + amount)),
        max(0, min(255, color[1] + amount)),
        max(0, min(255, color[2] + amount)),
        color[3],
    )


def add_alpha(color: tuple[int, int, int, int], alpha: int) -> tuple[int, int, int, int]:
    return (color[0], color[1], color[2], max(0, min(255, alpha)))


