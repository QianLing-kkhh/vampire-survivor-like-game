def render_burst(width: int, height: int, color: tuple[int, int, int, int], rings: int, frame: int = 0) -> Image.Image:
    image = transparent_canvas(width, height)
    draw = ImageDraw.Draw(image, "RGBA")
    cx, cy = width / 2, height / 2
    max_radius = min(width, height) * (0.22 + 0.09 * frame)
    for ring in range(rings):
        radius = max_radius + ring * 7
        alpha = max(35, 220 - ring * 55 - frame * 24)
        draw.ellipse((cx - radius, cy - radius, cx + radius, cy + radius), outline=add_alpha(color, alpha), width=max(2, rings - ring))
    for i in range(8):
        angle = math.tau * i / 8 + frame * 0.15
        r1 = max_radius * 0.25
        r2 = max_radius * (0.85 + rings * 0.08)
        draw.line((cx + math.cos(angle) * r1, cy + math.sin(angle) * r1, cx + math.cos(angle) * r2, cy + math.sin(angle) * r2), fill=add_alpha(color, 170), width=2)
    for i in range(12):
        angle = math.tau * i / 12 + frame * 0.37
        radius = max_radius * (0.45 + (i % 3) * 0.22)
        x = cx + math.cos(angle) * radius
        y = cy + math.sin(angle) * radius
        draw.rectangle((x - 1, y - 1, x + 1, y + 1), fill=add_alpha(shade(color, 70), max(70, 220 - frame * 35)))
    return image


