def direction_dx(direction: str) -> int:
    return -1 if "left" in direction else 1 if "right" in direction else 0


def direction_dy(direction: str) -> int:
    if direction.startswith("up"):
        return -1
    if direction.startswith("down"):
        return 1
    return 0


def stack_direction_sheets(sheets: list[Image.Image]) -> Image.Image:
    out = transparent_canvas(320, 80 * len(sheets))
    for index, sheet in enumerate(sheets):
        out.alpha_composite(sheet, (0, index * 80))
    return out


