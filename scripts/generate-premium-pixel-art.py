def weapon_from_key(key: str, path: str) -> str:
    source = f"{key}_{path}"
    for weapon in sorted(WEAPON_IDS, key=len, reverse=True):
        if weapon in source:
            return weapon
    return "knife"


def passive_from_key(key: str, path: str) -> str:
    source = f"{key}_{path}"
    for passive in PASSIVE_IDS:
        if passive in source:
            return passive
    return "spinach"


def enemy_from_key(key: str, path: str) -> str:
    source = f"{key}_{path}"
    if "lava" in source or "boss" in source:
        return "boss"
    if "bat" in source:
        return "bat"
    if "golem" in source:
        return "golem"
    return "slime"


